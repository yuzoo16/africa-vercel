# --- SLUG NORMALIZATION: the English slug is the permanent route identifier ---
# The tables above map an English slug to a per-language translation, and every
# consumer builds a FILESYSTEM PATH from that value:
#     $outdir=$lang+"/"+$HUB[$dir][$lang]   ->  New-Item -Path $outdir
#     $phre+='... href=".../'+$g2+'/'+$HUB[$cdir][$g2]+'/..."'
# Deriving a URL from a translated string is the root cause of /de/tansania-safari/.
#
# Forcing each table to return its own key leaves the dictionaries in place (so
# nothing that reads them breaks) while making it structurally impossible for a
# slug to be translated again. Referenced directly rather than by name via
# Get-Variable so scope resolution cannot fail when this file is dot-sourced.
#
# Deliberately excluded, because they are not path data and must never be
# altered: $DAYW/$SLUGTOK/$MONTHSLUG (slug fragments consumed only by the $MAP
# normalizer in i18n-urlmap.ps1) and $TOPICTOK (defined but never read).
foreach ($__tbl in @($HUB,$PARKSLUG,$ACTSLUG,$KILISLUG,$MIGSLUG,$GUIDESLUG,$ACCSLUG,$BLOGSLUG,$BLOGCAT)) {
  foreach ($__k in @($__tbl.Keys)) {
    $__inner = $__tbl[$__k]
    if ($__inner -is [System.Collections.IDictionary]) {
      foreach ($__g in @($__inner.Keys)) { $__inner[$__g] = $__k }
    }
  }
}
Remove-Variable __tbl,__k,__inner,__g -ErrorAction SilentlyContinue
